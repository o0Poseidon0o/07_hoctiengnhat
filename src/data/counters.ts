export interface CounterEntry {
  value: string;
  kanji: string;
  reading: string;
  romaji: string;
  /** True when the reading is irregular or has sound-change (biến âm / っ / 濁音). */
  special?: boolean;
  note?: string;
}

export interface CounterCategory {
  id: string;
  title: string;
  kanjiBadge: string;
  questionWord: string;
  questionReading: string;
  questionMeaning: string;
  /** Bold, large formula shown prominently at the top of the card. */
  formula: string;
  ruleSummary: string;
  memoryTip: string;
  entries: CounterEntry[];
}

export interface CounterQuiz {
  id: string;
  category: string;
  prompt: string;
  highlight?: string;
  options: string[];
  answerIndex: number;
  explanation: string;
}

